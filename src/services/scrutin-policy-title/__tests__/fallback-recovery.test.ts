import { describe, it, expect } from "vitest";
import {
  checkManualTitle,
  isOutageFallbackRow,
  type FallbackRowShape,
} from "@/services/scrutin-policy-title/fallback-recovery";
import type { EvidenceQuote, SubstanceTextBlock } from "@/services/scrutin-policy-title/types";

const outageRow = (over: Partial<FallbackRowShape> = {}): FallbackRowShape => ({
  status: "NEEDS_REVIEW",
  generationSource: "FALLBACK",
  policyTitle: null,
  generatedAt: new Date("2026-11-14T10:00:00.000Z"),
  generationWarnings: [
    { code: "LLM_OUTPUT_INVALID", severity: "blocker", message: "Sortie LLM invalide" },
  ],
  ...over,
});

describe("isOutageFallbackRow", () => {
  it("keeps a fallback row of the outage window", () => {
    expect(isOutageFallbackRow(outageRow())).toBe(true);
  });

  it("includes the first instant of the window and excludes its end", () => {
    expect(isOutageFallbackRow(outageRow({ generatedAt: new Date("2026-11-12T00:00:00Z") }))).toBe(
      true
    );
    expect(isOutageFallbackRow(outageRow({ generatedAt: new Date("2026-11-18T00:00:00Z") }))).toBe(
      false
    );
  });

  it("leaves out older fallback rows, whose cause is missing substance", () => {
    expect(
      isOutageFallbackRow(
        outageRow({
          generatedAt: new Date("2026-11-01T10:00:00Z"),
          generationWarnings: [{ code: "NO_SUBSTANCE", severity: "blocker", message: "" }],
        })
      )
    ).toBe(false);
  });

  it("requires the invalid-output warning", () => {
    expect(isOutageFallbackRow(outageRow({ generationWarnings: [] }))).toBe(false);
    expect(isOutageFallbackRow(outageRow({ generationWarnings: null }))).toBe(false);
  });

  it("skips rows already titled, approved or generated by the model", () => {
    expect(isOutageFallbackRow(outageRow({ policyTitle: "Un titre" }))).toBe(false);
    expect(isOutageFallbackRow(outageRow({ status: "APPROVED" }))).toBe(false);
    expect(isOutageFallbackRow(outageRow({ generationSource: "LLM" }))).toBe(false);
  });
});

const block: SubstanceTextBlock = {
  sourceType: "amendment",
  sourceId: "amd-1",
  field: "Amendment.summary",
  text: "Cet amendement supprime l'exonération de taxe foncière accordée aux entrepôts logistiques.",
  trust: "official",
};
const quote: EvidenceQuote = {
  sourceType: "amendment",
  sourceId: "amd-1",
  field: "Amendment.summary",
  quote: "supprime l'exonération de taxe foncière accordée aux entrepôts logistiques",
};
const OFFICIAL = "Amendement n° 12 à l'article 4 du projet de loi de finances pour 2027";

describe("checkManualTitle", () => {
  it("accepts a grounded title", () => {
    const r = checkManualTitle(
      {
        title: "Supprimer l'exonération de taxe foncière des entrepôts logistiques",
        evidenceQuotes: [quote],
      },
      [block],
      OFFICIAL
    );
    expect(r.ok).toBe(true);
  });

  it("blocks a title without quotes, as a fallback row has none of its own", () => {
    const r = checkManualTitle(
      { title: "Supprimer l'exonération de taxe foncière des entrepôts logistiques" },
      [block],
      OFFICIAL
    );
    expect(r).toMatchObject({ ok: false, reason: expect.stringContaining("EVIDENCE_GROUNDING") });
  });

  it("blocks a quote that is not in the cited block", () => {
    const r = checkManualTitle(
      {
        title: "Supprimer l'exonération de taxe foncière des entrepôts logistiques",
        evidenceQuotes: [{ ...quote, quote: "accorde une exonération nouvelle" }],
      },
      [block],
      OFFICIAL
    );
    expect(r).toMatchObject({ ok: false, reason: expect.stringContaining("EVIDENCE_GROUNDING") });
  });

  it("rejects an empty or over-long title before running validators", () => {
    expect(checkManualTitle({ title: "  " }, [block], OFFICIAL)).toMatchObject({
      ok: false,
      reason: "EMPTY_TITLE",
    });
    expect(
      checkManualTitle({ title: "x".repeat(141), evidenceQuotes: [quote] }, [block], OFFICIAL)
    ).toMatchObject({ ok: false, reason: "OVER_LENGTH" });
  });

  it("trims the title and turns a blank subtitle into null", () => {
    const r = checkManualTitle(
      {
        title: "  Supprimer l'exonération de taxe foncière des entrepôts logistiques ",
        subtitle: " ",
        evidenceQuotes: [quote],
      },
      [block],
      OFFICIAL
    );
    expect(r).toMatchObject({
      ok: true,
      title: "Supprimer l'exonération de taxe foncière des entrepôts logistiques",
      subtitle: null,
    });
  });
});
