/**
 * Exports the design tokens declared in src/app/globals.css, the brand constants, the data
 * palettes of src/config/colors.ts and the party colours to docs/design/tokens.generated.json.
 *
 * Why: designers and design tools need the tokens in a machine-readable file that cannot
 * drift from the code. The CSS stays the source of truth; this file is derived from it.
 *
 *   npm run design:tokens          rewrite the file
 *   npm run design:tokens:check    fail (exit 1) when the committed file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(__dirname, "..");
const CSS_PATH = resolve(ROOT, "src/app/globals.css");
const BRAND_PATH = resolve(ROOT, "src/config/brand.ts");
const COLORS_PATH = resolve(ROOT, "src/config/colors.ts");
const PARTY_PATH = resolve(ROOT, "src/config/party-colors.ts");
const OUT_PATH = resolve(ROOT, "docs/design/tokens.generated.json");

type TokenMap = Record<string, string>;

function stripComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, "");
}

// Reads the custom properties of the top-level block opened by `selector`.
// Nested blocks are not expected in :root and .dark, so a flat match is enough.
function readBlock(css: string, selector: RegExp): TokenMap {
  const tokens: TokenMap = {};
  const pattern = new RegExp(`(?:^|\\n)\\s*${selector.source}\\s*\\{([^{}]*)\\}`, "g");
  for (const match of css.matchAll(pattern)) {
    for (const declaration of match[1].split(";")) {
      const separator = declaration.indexOf(":");
      const name = declaration.slice(0, separator).trim();
      if (separator === -1 || !name.startsWith("--")) continue;
      tokens[name.slice(2)] = declaration
        .slice(separator + 1)
        .replace(/\s+/g, " ")
        .trim();
    }
  }
  return tokens;
}

function readBrand(source: string): TokenMap {
  const brand: TokenMap = {};
  for (const match of source.matchAll(/export const (BRAND_[A-Z_]+) = "(#[0-9a-fA-F]{6})"/g)) {
    brand[match[1]] = match[2].toLowerCase();
  }
  return brand;
}

type Palette = Record<string, Record<string, { light: string; dark: string }>>;

// Reads the COLORS object of colors.ts: category -> key -> { light, dark }.
// Entries without a dark variant do not exist in that file, so every entry has both.
function readPalettes(source: string): Palette {
  const start = source.indexOf("export const COLORS = {");
  const end = source.indexOf("} as const;", start);
  if (start === -1 || end === -1) throw new Error("COLORS object not found in colors.ts");
  const palettes: Palette = {};
  let category = "";
  for (const line of source.slice(start, end).split("\n")) {
    const header = line.match(/^ {2}(\w+): \{\s*$/);
    if (header) {
      category = header[1];
      palettes[category] = {};
      continue;
    }
    const entry = line.match(
      /^ {4}(\w+): \{ light: "(#[0-9a-fA-F]{6})", dark: "(#[0-9a-fA-F]{6})"/
    );
    if (entry && category) {
      palettes[category][entry[1]] = {
        light: entry[2].toLowerCase(),
        dark: entry[3].toLowerCase(),
      };
    }
  }
  return palettes;
}

// Reads PARTY_COLORS of party-colors.ts: party code -> hex. Parties keep their own brand hex in both themes.
function readParties(source: string): TokenMap {
  const start = source.indexOf("export const PARTY_COLORS");
  const end = source.indexOf("};", start);
  const parties: TokenMap = {};
  for (const match of source
    .slice(start, end)
    .matchAll(/\b([A-Z][A-Z0-9_]*): "(#[0-9a-fA-F]{6})"/g)) {
    parties[match[1]] = match[2].toLowerCase();
  }
  return parties;
}

export function buildTokens(): string {
  const css = stripComments(readFileSync(CSS_PATH, "utf8"));
  const document = {
    $comment:
      "Generated by scripts/export-design-tokens.ts from src/app/globals.css, src/config/{brand,colors,party-colors}.ts. Do not edit by hand.",
    brand: readBrand(readFileSync(BRAND_PATH, "utf8")),
    palettes: readPalettes(readFileSync(COLORS_PATH, "utf8")),
    parties: readParties(readFileSync(PARTY_PATH, "utf8")),
    themes: {
      light: readBlock(css, /:root/),
      dark: readBlock(css, /\.dark/),
    },
  };
  return `${JSON.stringify(document, null, 2)}\n`;
}

function main() {
  const next = buildTokens();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT_PATH, "utf8");
    } catch {
      // A missing file is stale by definition.
    }
    if (current !== next) {
      console.error(
        "docs/design/tokens.generated.json is out of date with src/app/globals.css.\n" +
          "Run `npm run design:tokens` and commit the result."
      );
      process.exit(1);
    }
    console.log("Design tokens export is up to date.");
    return;
  }
  writeFileSync(OUT_PATH, next);
  console.log(`Wrote ${OUT_PATH}`);
}

if (require.main === module) main();
